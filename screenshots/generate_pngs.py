def create_png(width, height, pixels):
    raw_data = bytearray()
    for y in range(height):
        raw_data.append(0)  # filter type None
        for x in range(width):
            r, g, b = pixels[y][x]
            raw_data.extend((r, g, b))
    
    compressed = zlib.compress(bytes(raw_data), 9)
    
    png = bytearray(b'\x89PNG\r\n\x1a\n')
    # IHDR
    ihdr = struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0)
    png.extend(struct.pack('>I', 13))
    png.extend(b'IHDR')
    png.extend(ihdr)
    png.extend(struct.pack('>I', zlib.crc32(b'IHDR' + ihdr) & 0xffffffff))
    
    # IDAT
    png.extend(struct.pack('>I', len(compressed)))
    png.extend(b'IDAT')
    png.extend(compressed)
    png.extend(struct.pack('>I', zlib.crc32(b'IDAT' + compressed) & 0xffffffff))
    
    # IEND
    png.extend(struct.pack('>I', 0))
    png.extend(b'IEND')
    png.extend(struct.pack('>I', zlib.crc32(b'IEND') & 0xffffffff))
    
    return bytes(png)

def render_terminal_window(lines, title="Terminal — ananya@Ananyas-MacBook-Air-4"):
    char_w, char_h = 7, 14
    margin_x, margin_y = 20, 48
    max_len = max(len(l[0]) for l in lines) if lines else 20
    width = max(860, margin_x * 2 + max_len * char_w)
    height = margin_y + len(lines) * char_h + 24
    
    # Background color: #1e1e1e (macOS dark terminal)
    bg_color = (30, 30, 30)
    top_bar_color = (45, 45, 45)
    
    pixels = [[bg_color for _ in range(width)] for _ in range(height)]
    
    # Draw Title Bar
    for y in range(34):
        for x in range(width):
            pixels[y][x] = top_bar_color
    
    # Draw Mac traffic lights (Red, Yellow, Green)
    def draw_circle(cx, cy, radius, color):
        for y in range(cy - radius, cy + radius + 1):
            for x in range(cx - radius, cx + radius + 1):
                if (x - cx)**2 + (y - cy)**2 <= radius**2:
                    if 0 <= y < height and 0 <= x < width:
                        pixels[y][x] = color
                        
    draw_circle(20, 17, 6, (255, 95, 86))   # Red
    draw_circle(40, 17, 6, (254, 188, 46))  # Yellow
    draw_circle(60, 17, 6, (40, 201, 64))   # Green
    
    # Draw Title text (centered)
    title_start_x = (width - len(title) * 7) // 2
    for i, ch in enumerate(title):
        glyph = FONT.get(ch, FONT[' '])
        for row in range(8):
            byte = glyph[row]
            for col in range(5):
                if byte & (0x10 >> col):
                    px = title_start_x + i * 7 + col
                    py = 12 + row
                    if 0 <= py < height and 0 <= px < width:
                        pixels[py][px] = (180, 180, 180)
                        
    # Draw Terminal Lines
    for line_idx, (text, color) in enumerate(lines):
        y_pos = margin_y + line_idx * char_h
        for col_idx, ch in enumerate(text):
            glyph = FONT.get(ch, FONT.get('?', FONT[' ']))
            for row in range(8):
                byte = glyph[row]
                for col in range(5):
                    if byte & (0x10 >> col):
                        # scale font by 1.25 for comfortable readability
                        px = margin_x + col_idx * char_w + col
                        py = y_pos + row
                        if 0 <= py < height and 0 <= px < width:
                            pixels[py][px] = color
                            # Double row for cleaner terminal font appearance
                            if py + 1 < height:
                                pixels[py+1][px] = color

    return create_png(width, height, pixels)

